// Generates the flat Studio command-bar script (the `lua` field / .lua export).
// Values are re-serialized from parsed literals, so only constructors and literals reach the output.
import { isScript, pinnedProps } from './classes';
import type { Inst } from './instance';
import { luaString, toLiteral } from './literal';

/** Long-bracket string that cannot be closed early by its own content. */
export function longString(s: string): string {
  let eq = '=';
  while (s.includes(`]${eq}]`)) eq += '=';
  // A newline right after the opening bracket is dropped by Lua, so add one to keep the source exact.
  return `[${eq}[\n${s}]${eq}]`;
}

const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/;

export function generateLua(root: Inst): string {
  const lines: string[] = [
    `-- ${root.name} — generated by Roblox UI Builder (rblxui/1.0).`,
    '-- Paste into the Roblox Studio command bar (View > Command Bar). Creates the ScreenGui under StarterGui.',
    'local n = {}',
    'local function make(i, class, parent, props)',
    '\tlocal o = Instance.new(class)',
    '\tfor k, v in props do o[k] = v end',
    '\t-- CanvasPosition is clamped to CanvasSize, so apply it after everything else',
    '\tif props.CanvasPosition then o.CanvasPosition = props.CanvasPosition end',
    '\tn[i] = o',
    '\tif parent then o.Parent = n[parent] end',
    'end',
  ];
  let next = 0;
  const emit = (inst: Inst, parent: number | null) => {
    const i = ++next;
    const fields = [`Name = ${luaString(inst.name)}`];
    const keys = new Set([...pinnedProps(inst.className).filter((k) => inst.get(k) !== undefined), ...inst.props.keys()]);
    for (const k of keys) {
      const v = inst.get(k);
      if (k === 'Source' || v === null || v === undefined || (typeof v === 'object' && v.t === 'Ref')) continue;
      fields.push(`${IDENT.test(k) ? k : `[${luaString(k)}]`} = ${toLiteral(v)}`);
    }
    if (isScript(inst.className)) fields.push(`Source = ${longString(String(inst.get('Source') ?? ''))}`);
    lines.push(`make(${i}, ${luaString(inst.className)}, ${parent ?? 'nil'}, { ${fields.join(', ')} })`);
    for (const [k, v] of inst.attrs) lines.push(`n[${i}]:SetAttribute(${luaString(k)}, ${toLiteral(v)})`);
    for (const c of inst.children) emit(c, i);
  };
  emit(root, null);
  lines.push('n[1].Parent = game:GetService("StarterGui")');
  lines.push('print("Created StarterGui." .. n[1].Name)');
  return lines.join('\n') + '\n';
}
